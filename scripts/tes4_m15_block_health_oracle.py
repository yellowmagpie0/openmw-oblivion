"""Regenerate M15 block Health expectations from a hash-identified original PE.

Requires Unicorn. Executes only5FF8F3->5FF914 with prescribed stack inputs;
never calls production C++ or writes original game files. Live input evidence
and actual engine/runtime acceptance are separate from this arithmetic probe.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import random
import struct

EXECUTABLE_SHA256 = 'a8f313845c1545e9a60e1e995961eef4c033115da9443f6d756341df3c2b7dc6'
HEADER = ('// Original5FF8F3->5FF914, PC24 observed in two normal original Player blocks.\n'
          '// Generated by independent original-instruction oracle; see M15-BLOCK-HEALTH-PRECISION-VERIFICATION.json.\n')


def probe(executable: Path, recipe: dict, repo: Path) -> tuple[str, dict]:
    if (recipe['schema_version'] != 1 or recipe['executable_sha256'] != EXECUTABLE_SHA256
            or recipe['control_word'] != 127 or recipe['native_slice'] != [0x5ff8f3, 0x5ff914]
            or recipe['stack_input_offsets'] != [0x18, 0x30] or recipe['stack_output_offset'] != 0x18):
        raise ValueError('unsupported block Health probe identity')
    helper = repo / '.codex/skills/oblivion-native-oracle/scripts/inspect_pe.py'
    spec = importlib.util.spec_from_file_location('m15_block_health_pe', helper)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    identity = module.inspect(executable, EXECUTABLE_SHA256)
    from unicorn import Uc, UC_ARCH_X86, UC_MODE_32
    from unicorn.x86_const import UC_X86_REG_ESP, UC_X86_REG_FPCW, UC_X86_REG_FPTAG, UC_X86_REG_FPSW, UC_X86_REG_EIP
    image = executable.read_bytes()
    if hashlib.sha256(image).hexdigest() != EXECUTABLE_SHA256:
        raise ValueError('executable changed after identity check')
    emulator = Uc(UC_ARCH_X86, UC_MODE_32)
    emulator.mem_map(identity['image_base'], (identity['image_size'] + 4095) & ~4095)
    for _, address, offset, size in identity['sections']:
        if size:
            emulator.mem_write(address, image[offset:offset + size])
    emulator.mem_map(0x2000000, 0x10000)
    stack = 0x2008000
    pairs = {tuple(row[:2]) for row in recipe['observed_inputs'] + recipe['composed_inputs']}
    pairs.update((damage, fraction) for damage in recipe['edge_damage_bits'] for fraction in recipe['edge_fraction_bits'])
    rng = random.Random(recipe['seed'])
    for _ in range(recipe['generated_pairs']):
        pairs.add((rng.randrange(0x7f800000), rng.randrange(0x3f800001)))
    rows = []
    for damage, fraction in sorted(pairs):
        values = [struct.unpack('<f', struct.pack('<I', value))[0] for value in (damage, fraction)]
        if not all(math.isfinite(v) and v >= 0 for v in values) or values[1] > 1:
            raise ValueError('unsupported block Health input')
        for register, value in [(UC_X86_REG_ESP, stack), (UC_X86_REG_FPCW, 0x7f),
                                (UC_X86_REG_FPTAG, 0xffff), (UC_X86_REG_FPSW, 0)]:
            emulator.reg_write(register, value)
        emulator.mem_write(stack + 0x18, struct.pack('<I', damage))
        emulator.mem_write(stack + 0x30, struct.pack('<I', fraction))
        emulator.emu_start(0x5ff8f3, 0x5ff914, count=100)
        if emulator.reg_read(UC_X86_REG_EIP) != 0x5ff914:
            raise RuntimeError('original block Health slice did not reach its store boundary')
        result = struct.unpack('<I', bytes(emulator.mem_read(stack + 0x18, 4)))[0]
        rows.append((damage, fraction, result))
    if len(rows) != recipe['expected_cases']:
        raise ValueError('block Health inventory differs')
    for observed in recipe['observed_inputs']:
        if tuple(observed) not in rows:
            raise ValueError('original arithmetic differs from a captured live contact')
    corpus = HEADER + ''.join('{0x%08xu, 0x%08xu, 0x%08xu},\n' % row for row in rows)
    return corpus, dict(passed=True, cases=len(rows), control_word=127, executable=identity,
                        corpus_sha256=hashlib.sha256(corpus.encode()).hexdigest(),
                        scope='Prescribed original Health arithmetic only; no calls or boundary stubs inside the slice. Live observation and production runtime acceptance are separate.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('executable', type=Path)
    parser.add_argument('output', type=Path, help='New evidence directory')
    repo = Path(__file__).resolve().parents[1]
    parser.add_argument('--recipe', type=Path, default=repo / 'scripts/data/oblivion_compat/m15_block_health_native_probe.json')
    args = parser.parse_args()
    corpus, report = probe(args.executable, json.loads(args.recipe.read_text()), repo)
    args.output.mkdir(parents=True, exist_ok=False)
    (args.output / 'blockhealth_expected.inc').write_text(corpus)
    (args.output / 'verification.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(dict(passed=True, cases=report['cases'], corpus_sha256=report['corpus_sha256'])))


if __name__ == '__main__':
    main()
